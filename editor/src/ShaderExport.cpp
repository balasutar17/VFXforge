std::string safeName(const std::string& name) {
    std::string out;
    for (unsigned char c : name) {
        if (std::isalnum(c) || c == '_') {
            out += static_cast<char>(c);
        } else if (!out.empty() && out.back() != '_') {
            out += '_';
        }
    }
    while (!out.empty() && out.back() == '_') out.pop_back();
    if (out.empty()) out = "Shader";
    if (std::isdigit(static_cast<unsigned char>(out[0]))) out = "S_" + out;
    return out;
}

std::string shaderGuid(const std::string& name) {
    return hex16(fnv("vfxforge.shader:" + name, 1469598103934665603ull)) + hex16(fnv(name + ":guid", 7809847782465536322ull));
}

std::string generateShader(const Settings& s) {
    const Family* family = findFamily(s.family);
    if (!family) return {};
    const std::string name = safeName(s.name);
    const std::vector<std::array<float, 4>> now = valuesAt(s, 0.0);
    const bool ui = family->isUi, particle = family->isParticle;
    const int quality = std::clamp(s.quality, 0, 3);
    std::ostringstream o;
    o.imbue(std::locale::classic());
    o << "// Generated by VFX Forge (Shader tab): " << clean(s.name) << " (" << clean(family->name) << ", preset " << clean(s.preset) << ").\n"
      << "// The maths below is the same source the VFX Forge preview runs. Change values on the\n"
      << "// material, or in VFX Forge and export again; editing the code here is lost on re-export.\n"
      << "// Two sub shaders: Universal Render Pipeline (UniversalForward pass) and Built-in (UI shaders: Built-in only).\n";
    o << "Shader \"VFX Forge/Shaders/" << name << "\"\n{\n    Properties\n    {\n";
    for (const ParamDef& p : family->params) {
        const auto v = valueOf(now, p);
        if (p.kind == ParamKind::Color) {
            o << "        [HDR] " << propName(p) << " (\"" << clean(p.label) << "\", Color) = (" << num(v[0]) << "," << num(v[1]) << "," << num(v[2]) << "," << num(v[3]) << ")\n";
        } else if (p.kind == ParamKind::Choice) {
            o << "        [Enum(" << enumList(p) << ")] " << propName(p) << " (\"" << clean(p.label) << "\", Float) = " << num(v[0]) << "\n";
        } else {
            o << "        " << propName(p) << " (\"" << clean(p.label) << "\", Range(" << num(p.min) << ", " << num(p.max) << ")) = " << num(v[0]) << "\n";
        }
    }
    if (ui) {
        o << "        [PerRendererData] _MainTex (\"Sprite\", 2D) = \"white\" {}\n"
          << "        [PerRendererData] _Color (\"Tint\", Color) = (1,1,1,1)\n"
          << "        [HideInInspector] _StencilComp (\"Stencil Comparison\", Float) = 8\n"
          << "        [HideInInspector] _Stencil (\"Stencil ID\", Float) = 0\n"
          << "        [HideInInspector] _StencilOp (\"Stencil Operation\", Float) = 0\n"
          << "        [HideInInspector] _StencilWriteMask (\"Stencil Write Mask\", Float) = 255\n"
          << "        [HideInInspector] _StencilReadMask (\"Stencil Read Mask\", Float) = 255\n"
          << "        [HideInInspector] _ColorMask (\"Color Mask\", Float) = 15\n";
    }
    o << "        [HideInInspector] _BoundsCenter (\"Bounds centre\", Vector) = (0,0,0,0)\n"
      << "        [HideInInspector] _BoundsExtent (\"Bounds half size\", Float) = 0.5\n"
      << "        [HideInInspector] _HitPos (\"Impact direction\", Vector) = (0.55,0.55,0.62,0)\n"
      << "        [HideInInspector] _HitAge (\"Impact age (negative: none)\", Float) = -1\n"
      << "        [HideInInspector] _ScriptTime (\"Time from the Shader Animator\", Float) = 0\n"
      << "        [HideInInspector] _UseScriptTime (\"Use the Shader Animator's time\", Float) = 0\n"
      << "        [HideInInspector] _UseAge (\"Particle age from the AgePercent stream\", Float) = 0\n"
      << "        [HideInInspector] _Lifetime (\"Seconds per cycle without a stream\", Float) = " << num(s.animation.duration) << "\n"
      << "        [HideInInspector] _Burst (\"Burst brightness\", Float) = 0\n"
      << "    }\n\n";
    // One file serves both pipelines: the URP sub shader first (Unity picks the first that suits the
    // project's pipeline), then the Built-in one. The UI family has only the Built-in one: Canvas
    // UI is drawn by the Built-in UI path in URP too.
    auto sub = [&](bool urp) {
    o << "    SubShader\n    {\n";
    if (ui) {
        o << "        Tags { \"Queue\" = \"Transparent\" \"IgnoreProjector\" = \"True\" \"RenderType\" = \"Transparent\" \"PreviewType\" = \"Plane\" \"CanUseSpriteAtlas\" = \"True\" }\n"
          << "        Stencil\n        {\n            Ref [_Stencil]\n            Comp [_StencilComp]\n            Pass [_StencilOp]\n            ReadMask [_StencilReadMask]\n            WriteMask [_StencilWriteMask]\n        }\n"
          << "        Cull Off\n        Lighting Off\n        ZWrite Off\n        ZTest [unity_GUIZTestMode]\n        ColorMask [_ColorMask]\n";
    } else {
        o << "        Tags { " << (urp ? "\"RenderPipeline\" = \"UniversalPipeline\" " : "") << "\"Queue\" = \"Transparent\" \"IgnoreProjector\" = \"True\" \"RenderType\" = \"Transparent\" }\n"
          << "        Cull " << (family->cullOff ? "Off" : "Back") << "\n        ZWrite " << (family->zwrite ? "On" : "Off") << "\n";
    }
    o << "        Blend SrcAlpha " << (s.blend == BlendMode::Additive ? "One" : "OneMinusSrcAlpha") << "\n\n";
    if (urp) {
        o << "        Pass\n        {\n            Name \"VFXForgeUnlit\"\n            Tags { \"LightMode\" = \"UniversalForward\" }\n"
          << "            HLSLPROGRAM\n            #pragma vertex vert\n            #pragma fragment frag\n            #pragma target 3.0\n"
          << "            #include \"Packages/com.unity.render-pipelines.universal/ShaderLibrary/Core.hlsl\"\n";
    } else {
        o << "        Pass\n        {\n            CGPROGRAM\n            #pragma vertex vert\n            #pragma fragment frag\n            #pragma target 3.0\n";
    }
    if (ui) o << "            #pragma multi_compile_local _ UNITY_UI_CLIP_RECT\n            #pragma multi_compile_local _ UNITY_UI_ALPHACLIP\n";
    if (!urp) o << "            #include \"UnityCG.cginc\"\n";
    if (ui) o << "            #include \"UnityUI.cginc\"\n";
    o << "\n            #define VFX_OCTAVES " << qualityProfiles()[static_cast<std::size_t>(quality)].octaves << "\n"
      << "            #define VFX_QUALITY " << quality << "\n\n";
    // Parameter indices of every family: the shared source mentions all of them.
    for (const Family& f : families()) {
        for (const ParamDef& p : f.params) o << "            #define " << p.macro << " " << p.index << "\n";
    }
    o << "\n";
    if (urp) o << "            CBUFFER_START(UnityPerMaterial)\n";
    for (const ParamDef& p : family->params) {
        o << "            " << (p.kind == ParamKind::Color ? "float4 " : "float ") << propName(p) << ";\n";
    }
    o << "            float4 _BoundsCenter;\n            float _BoundsExtent;\n            float4 _HitPos;\n            float _HitAge;\n"
      << "            float _ScriptTime;\n            float _UseScriptTime;\n            float _UseAge;\n            float _Lifetime;\n            float _Burst;\n";
    if (urp) o << "            CBUFFER_END\n";
    if (ui) o << "            sampler2D _MainTex;\n            fixed4 _Color;\n            float4 _ClipRect;\n";
    o << "\n// ---- shared shader source (editor/shaders/ShaderCore.hlsli) ----\n"
      << shaderCoreSource() << "\n// ---- end of shared source ----\n\n";
    o << "            Params BuildParams()\n            {\n                Params P = (Params)0;\n";
    for (const ParamDef& p : family->params) {
        o << "                P.v[" << p.macro << "] = " << (p.kind == ParamKind::Color ? propName(p) : "float4(" + propName(p) + ", 0, 0, 0)") << ";\n";
    }
    o << "                return P;\n            }\n\n";
    if (ui) {
        o << "            struct appdata_t\n            {\n                float4 vertex : POSITION;\n                float4 color : COLOR;\n                float2 texcoord : TEXCOORD0;\n                UNITY_VERTEX_INPUT_INSTANCE_ID\n            };\n"
          << "            struct v2f\n            {\n                float4 vertex : SV_POSITION;\n                fixed4 color : COLOR;\n                float2 texcoord : TEXCOORD0;\n                float4 worldPosition : TEXCOORD1;\n                UNITY_VERTEX_OUTPUT_STEREO\n            };\n\n"
          << "            v2f vert(appdata_t v)\n            {\n                v2f OUT;\n                UNITY_SETUP_INSTANCE_ID(v);\n                UNITY_INITIALIZE_VERTEX_OUTPUT_STEREO(OUT);\n"
          << "                OUT.worldPosition = v.vertex;\n                OUT.vertex = UnityObjectToClipPos(OUT.worldPosition);\n                OUT.texcoord = v.texcoord;\n                OUT.color = v.color * _Color;\n                return OUT;\n            }\n\n"
          << "            float spriteAlphaAt(float2 uv, Params P)\n            {\n                if (PF(UI_frameMode) > 0.5)\n                    return borderAlpha(uv, PF(UI_frameWidth), PF(UI_frameRadius));\n                return tex2Dlod(_MainTex, float4(uv, 0, 0)).a;\n            }\n\n"
          << "            fixed4 frag(v2f i) : SV_Target\n            {\n                Params P = BuildParams();\n                float t0 = _UseScriptTime > 0.5 ? _ScriptTime : _Time.y;\n"
          << "                ShadeIn I = (ShadeIn)0;\n                I.uv = i.texcoord;\n                I.nrm = float3(0, 0, 1);\n                I.view = float3(0, 0, 1);\n                I.t = t0 * PF(CM_speed);\n                I.hitAge = 1.0e6;\n"
          << "                I.spriteA = spriteAlphaAt(i.texcoord, P);\n                float ow = PF(UI_outlineWidth);\n                float outer = 0.0;\n                float glow = 0.0;\n"
          << "                [unroll] for (int k = 0; k < 8; k++)\n                {\n                    float ang = k * 0.7853982;\n                    float2 d = float2(cos(ang), sin(ang));\n"
          << "                    outer = max(outer, spriteAlphaAt(i.texcoord + d * ow, P));\n                    glow += spriteAlphaAt(i.texcoord + d * 0.05, P) + spriteAlphaAt(i.texcoord + d * 0.10, P);\n                }\n"
          << "                I.spriteOut = outer;\n                I.spriteGlow = glow / 16.0;\n"
          << "                ShadeOut o = " << shadeFunction(*family) << "(I, P);\n"
          << "                float4 c = float4(o.rgb * (1.0 + _Burst) * i.color.rgb, saturate(o.a) * i.color.a);\n"
          << "                #ifdef UNITY_UI_CLIP_RECT\n                c.a *= UnityGet2DClipping(i.worldPosition.xy, _ClipRect);\n                #endif\n"
          << "                #ifdef UNITY_UI_ALPHACLIP\n                clip(c.a - 0.001);\n                #endif\n                return c;\n            }\n";
    } else {
        o << "            struct appdata\n            {\n                float4 vertex : POSITION;\n                float3 normal : NORMAL;\n                float4 uv : TEXCOORD0;\n                float4 color : COLOR;\n            };\n"
          << "            struct v2f\n            {\n                float4 pos : SV_POSITION;\n                float3 opos : TEXCOORD0;\n                float3 onrm : TEXCOORD1;\n                float3 oview : TEXCOORD2;\n                float4 uv : TEXCOORD3;\n                float4 color : COLOR;\n            };\n\n"
          << "            v2f vert(appdata v)\n            {\n                v2f o;\n                o.pos = " << (urp ? "TransformObjectToHClip(v.vertex.xyz)" : "UnityObjectToClipPos(v.vertex)") << ";\n"
          << "                o.opos = (v.vertex.xyz - _BoundsCenter.xyz) / max(_BoundsExtent, 0.0001);\n                o.onrm = v.normal;\n                o.oview = " << (urp ? "TransformWorldToObject(GetCameraPositionWS()) - v.vertex.xyz" : "ObjSpaceViewDir(v.vertex)") << ";\n                o.uv = v.uv;\n                o.color = v.color;\n                return o;\n            }\n\n"
          << "            " << (urp ? "float4" : "fixed4") << " frag(v2f i) : SV_Target\n            {\n                Params P = BuildParams();\n                float t0 = _UseScriptTime > 0.5 ? _ScriptTime : _Time.y;\n"
          << "                ShadeIn I = (ShadeIn)0;\n                I.pos = i.opos;\n                I.nrm = normalize(i.onrm);\n                I.view = normalize(i.oview);\n                I.uv = i.uv.xy;\n                I.t = t0 * PF(CM_speed);\n"
          << "                I.hitPos = normalize(_HitPos.xyz);\n";
        if (family->id == "shield") {
            o << "                float autoHit = PF(FF_autoHit);\n"
              << "                // Without a Shader Animator on the object, repeat a test impact (as the VFX Forge preview does).\n"
              << "                I.hitAge = _HitAge >= 0.0 ? _HitAge : ((_UseScriptTime < 0.5 && autoHit > 0.05) ? t0 - autoHit * floor(t0 / autoHit) : 1.0e6);\n";
        } else {
            o << "                I.hitAge = 1.0e6;\n";
        }
        if (particle) {
            o << "                I.life = _UseAge > 0.5 ? saturate(i.uv.z) : frac(t0 / max(_Lifetime, 0.1));\n";
        }
        o << "                ShadeOut o = " << shadeFunction(*family) << "(I, P);\n"
          << "                float3 rgb = o.rgb * (1.0 + _Burst);\n";
        if (particle) {
            o << "                return " << (urp ? "float4" : "fixed4") << "(rgb * i.color.rgb, saturate(o.a) * i.color.a);\n";
        } else {
            o << "                return " << (urp ? "float4" : "fixed4") << "(rgb, saturate(o.a));\n";
        }
        o << "            }\n";
    }
    o << (urp ? "            ENDHLSL\n" : "            ENDCG\n") << "        }\n    }\n";
    };  // sub
    if (!ui) sub(true);
    sub(false);
    o << "    Fallback Off\n}\n";
    return o.str();
}

std::string generateMaterial(const Settings& s, const std::string& guid) {
    const Family* family = findFamily(s.family);
    if (!family) return {};
    const std::vector<std::array<float, 4>> now = valuesAt(s, 0.0);
    std::ostringstream o;
    o.imbue(std::locale::classic());
    o << "%YAML 1.1\n%TAG !u! tag:unity3d.com,2011:\n--- !u!21 &2100000\nMaterial:\n  serializedVersion: 8\n  m_ObjectHideFlags: 0\n"
      << "  m_CorrespondingSourceObject: {fileID: 0}\n  m_PrefabInstance: {fileID: 0}\n  m_PrefabAsset: {fileID: 0}\n"
      << "  m_Name: " << safeName(s.name) << "\n  m_Shader: {fileID: 4800000, guid: " << guid << ", type: 3}\n  m_Parent: {fileID: 0}\n"
      << "  m_ModifiedSerializedProperty: 0\n  m_ValidKeywords: []\n  m_InvalidKeywords: []\n  m_LightmapFlags: 4\n  m_EnableInstancingVariants: 0\n"
      << "  m_DoubleSidedGI: 0\n  m_CustomRenderQueue: 3000\n  stringTagMap: {}\n  disabledShaderPasses: []\n  m_LockedProperties: \n  m_SavedProperties:\n    serializedVersion: 3\n    m_TexEnvs:\n";
    if (family->isUi) {
        o << "    - _MainTex:\n        m_Texture: {fileID: 0}\n        m_Scale: {x: 1, y: 1}\n        m_Offset: {x: 0, y: 0}\n";
    } else {
        o << "    []\n";
    }
    o << "    m_Ints: []\n    m_Floats:\n";
    for (const ParamDef& p : family->params) {
        if (p.kind == ParamKind::Color) continue;
        o << "    - " << propName(p) << ": " << num(valueOf(now, p)[0]) << "\n";
    }
    o << "    - _BoundsExtent: 0.5\n    - _HitAge: -1\n    - _ScriptTime: 0\n    - _UseScriptTime: 0\n    - _UseAge: 0\n    - _Lifetime: " << num(s.animation.duration) << "\n    - _Burst: 0\n";
    if (family->isUi) {
        o << "    - _Stencil: 0\n    - _StencilComp: 8\n    - _StencilOp: 0\n    - _StencilReadMask: 255\n    - _StencilWriteMask: 255\n    - _ColorMask: 15\n";
    }
    o << "    m_Colors:\n";
    for (const ParamDef& p : family->params) {
        if (p.kind != ParamKind::Color) continue;
        const auto v = valueOf(now, p);
        o << "    - " << propName(p) << ": {r: " << num(v[0]) << ", g: " << num(v[1]) << ", b: " << num(v[2]) << ", a: " << num(v[3]) << "}\n";
    }
    o << "    - _BoundsCenter: {r: 0, g: 0, b: 0, a: 0}\n    - _HitPos: {r: 0.55, g: 0.55, b: 0.62, a: 0}\n";
    if (family->isUi) o << "    - _Color: {r: 1, g: 1, b: 1, a: 1}\n";
    o << "  m_BuildTextureStacks: []\n";
    return o.str();
}

std::string generateAnimationJson(const Settings& s) {
    using J = nlohmann::json;
    const Family* family = findFamily(s.family);
    J j;
    j["duration"] = s.animation.duration;
    j["loop"] = s.animation.loop == LoopMode::Loop ? 0 : s.animation.loop == LoopMode::PingPong ? 1 : 2;
    j["speed"] = s.animation.speed;
    j["revealProperty"] = "CM_reveal";
    j["hitRadiusProperty"] = family && family->id == "shield" ? "FF_hitRadius" : "";
    J tracks = J::array();
    if (family) {
        for (const Track& t : s.animation.tracks) {
            const ParamDef* p = findParam(*family, t.param);
            if (!p || p->kind == ParamKind::Color || t.keys.empty()) continue;
            J keys = J::array();
            for (const Key& k : t.keys) {
                keys.push_back({{"time", k.time}, {"value", k.value}, {"easing", static_cast<int>(k.easing)}});
            }
            tracks.push_back({{"property", p->macro}, {"min", p->min}, {"max", p->max}, {"keys", keys}});
        }
    }
    j["tracks"] = tracks;
    return j.dump(2) + "\n";
}

Result<ShaderExport> exportShader(const Settings& s) {
    const Family* family = findFamily(s.family);
    if (!family) return makeError("The shader family is not known, so nothing was exported.");
    if (s.values.size() != family->params.size()) {
        return makeError("The shader's settings do not match its family, so nothing was exported.", "Open the shader again or pick a preset.");
    }
    ShaderExport out;
    out.name = safeName(s.name);
    out.folder = "Shaders/" + out.name + "/";
    const std::string guid = shaderGuid(out.name);
    auto add = [&](const std::string& path, std::string text) { out.files.push_back({path, std::move(text)}); };
    add(out.folder + out.name + ".shader", generateShader(s));
    add(out.folder + out.name + ".shader.meta",
        "fileFormatVersion: 2\nguid: " + guid + "\nShaderImporter:\n  externalObjects: {}\n  defaultTextures: []\n  nonModifiableTextures: []\n  userData: \n  assetBundleName: \n  assetBundleVariant: \n");
    add(out.folder + out.name + ".mat", generateMaterial(s, guid));
    add(out.folder + out.name + ".vfxshader", writeSettings(s));
    add(out.folder + out.name + ".anim.json", generateAnimationJson(s));
    for (const UnityFile& f : unityHelperSources()) {
        if (f.path == "Runtime/VFXForgeShaderAnimator.cs" || f.path == "Runtime/VFXForgeShaderDemoHits.cs" || f.path == "Editor/VFXForgeShaderDemo.cs") out.files.push_back(f);
    }

    for (const std::string& n : validateSettings(s)) out.notes.push_back(n);
    for (const std::string& n : family->limits) out.notes.push_back(n);
    if (family->isUi) out.notes.push_back("Render pipeline: UI shaders are Built-in (Canvas) shaders; Unity's Canvas draws them in URP projects too. No HDRP and no Shader Graph version.");
    else out.notes.push_back("Render pipeline: the shader has a Universal Render Pipeline pass and a Built-in pass in one file; Unity uses the one that matches the project. The URP pass has not been compiled by Unity here (only checked as HLSL). No HDRP and no Shader Graph version.");
    out.notes.push_back("Glow above 1 is HDR. Turn on HDR and add a Bloom override (URP Volume or post-processing) to see the glow as in the preview; the preview's own bloom is not part of the shader.");
    if (family->isUi) {
        out.notes.push_back("UI: the shader reads the sprite's alpha at its own 0-1 texture coordinates. Set the sprite's Mesh Type to Full Rect and keep it out of a Sprite Atlas, or use Shape from: Border.");
    }
    if (family->id == "shield") {
        out.notes.push_back("Shield impacts: add the Shader Animator and call Hit(worldPosition, worldRadius). Without it the shader repeats a test impact every few seconds (Test impact every).");
    }
    if (family->isParticle) {
        out.notes.push_back("Particle: in the Particle System's Renderer module, add Custom Vertex Streams: Position, Color, UV, then AgePercent, and set Use Age to 1 on the material. Without it the colours cycle with time instead of each particle's life.");
    }
    if (s.animation.tracks.empty() == false) {
        out.notes.push_back("Keyframes play only with the Shader Animator component (it is exported with the shader); the .shader alone shows the values at time 0 and the procedural motion.");
    }

    std::ostringstream r;
    r << "VFX Forge shader: " << s.name << "\n"
      << "Family: " << family->name << "   Preset: " << s.preset << "   Quality profile: " << qualityProfiles()[static_cast<std::size_t>(std::clamp(s.quality, 0, 3))].name << "\n\n"
      << "SETUP\n"
      << "1. Copy the VFXForge folder into your project's Assets folder (this export already placed it there if you chose the project).\n"
      << "2. Use " << out.name << ".mat on a "
      << (family->isUi ? "UI Image (assign its sprite) or Sprite Renderer" : family->isParticle ? "Particle System renderer (Renderer > Material)" : "mesh: any MeshRenderer") << ".\n"
      << "3. To play the timeline and trigger events, add the 'VFX Forge/Shader Animator' component to the object and drag " << out.name << ".anim.json into its Animation File slot.\n"
      << "4. Quick demo: select " << out.name << ".mat in the Project window, then Assets > VFX Forge > Create Shader Demo Object.\n\n"
      << "SCRIPTING\n"
      << "  var anim = GetComponent<VFX" << "Forge.VFXForgeShaderAnimator>();\n"
      << "  anim.Hit(worldPoint, 0.5f);        // shield impact\n"
      << "  anim.Burst(1.5f, 0.5f);            // surge of brightness\n"
      << "  anim.Reveal(false, 0.8f);          // fade out (true fades in)\n\n"
      << "NOT SUPPORTED / THINGS TO KNOW\n";
    for (const std::string& n : out.notes) r << " - " << n << "\n";
    r << "\nSTATUS\nThe shader source is the same maths as VFX Forge's preview, but VFX Forge cannot run Unity: this export has not been opened in Unity by VFX Forge. If Unity reports a shader error, send the message so it can be fixed.\n";
    add(out.folder + "README.txt", r.str());
    return out;
}

