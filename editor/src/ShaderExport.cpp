std::string num(double v) {
    std::ostringstream o;
    o.imbue(std::locale::classic());
    o.precision(7);
    o << v;
    return o.str();
}

std::string clean(const std::string& s) {
    std::string out;
    for (char c : s) {
        if (c == '"' || c == '\\' || c == '\n' || c == '\r') continue;
        out += c;
    }
    return out;
}

std::string enumList(const ParamDef& p) {
    std::string out;
    for (std::size_t i = 0; i < p.choices.size(); ++i) {
        std::string c;
        for (char ch : p.choices[i]) c += (ch == ',' || ch == '(' || ch == ')' || ch == ']' || ch == '[') ? ' ' : ch;
        if (i) out += ",";
        out += c + "," + std::to_string(i);
    }
    return out;
}

std::string propName(const ParamDef& p) { return "_" + p.macro; }

const char* shadeFunction(const Family& f) { return f.function.c_str(); }

std::array<float, 4> valueOf(const std::vector<std::array<float, 4>>& v, const ParamDef& p) {
    if (static_cast<std::size_t>(p.index) < v.size()) return v[static_cast<std::size_t>(p.index)];
    return {static_cast<float>(p.def), 0, 0, 0};
}

std::string hex16(std::uint64_t v) {
    char buf[17];
    std::snprintf(buf, sizeof buf, "%016llx", static_cast<unsigned long long>(v));
    return buf;
}

std::uint64_t fnv(const std::string& s, std::uint64_t seed) {
    std::uint64_t h = seed;
    for (unsigned char c : s) {
        h ^= c;
        h *= 1099511628211ull;
    }
    return h;
}

